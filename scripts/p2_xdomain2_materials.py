#!/usr/bin/env python3
"""Blind annotation materials for the 6 true cross-domain chemistry points.

Reuses make_blind_materials.py redaction/leak-check logic verbatim. Points are
the 9 (task, step, parent_stamp) scan cells with complete 4-arm outcomes that
are OUTSIDE the 38 pre-registered points. Outputs:
reports/annotation/blind_materials_xdomain2.md (POINT 1-9, format identical to v2).
"""
import csv, json, re, sys
sys.path.insert(0, 'scripts')
from make_blind_materials import load_step_data, oneline
import re as _re
LEAK_RE2 = _re.compile(r"\b(frontier|resample|local_replace|frontier_hint|gpt-5|deepseek)\b|\bQwen\d|(?<!deter)mini(?!mum|mal)", _re.IGNORECASE)
def final_leak_check(text):
    return [m.group(0) for m in LEAK_RE2.finditer(text)]
import pandas as pd

PARQUET = '/data/lab/sab_data/verified.parquet'
OUT = 'reports/annotation/blind_materials_xdomain2.md'
# t40s5 and t60s9 are `kind: final` steps with no executable script; excluded so the
# held-out set matches the 38-point set (code steps only).
# True cross-domain set: all 3 code steps of the two chemistry parents
# (sab_1 @1792027104-2691932, sab_3 @1792027829-2732525). Pre-registered
# selection rule: every code step of the parent (final steps excluded).
HELD = [('1','1'),('1','2'),('1','3'),('3','1'),('3','2'),('3','3')]

PARENT_STAMP = {'1': '1792027104-2691932', '3': '1792027829-2732525'}
parent_of = {(task, step): f'runs/sab_{task}/frontier/{PARENT_STAMP[task]}'
             for task, step in HELD}
assert len(parent_of)==6, parent_of

desc = pd.read_parquet(PARQUET)
desc_by_id = {int(r['instance_id']): str(r['task_inst']) for _, r in desc.iterrows()}

out = ["# P2 cross-domain eval Blind Annotation Materials (v1)", "",
 "Generated by scripts/p2_xdomain_materials.py (deterministic; same redaction",
 "and blinding guarantees as blind_materials_v2.md). TASK-DESC is the benchmark",
 "task instruction verbatim.", ""]
for i, (task, step) in enumerate(HELD, 1):
    parent = parent_of[(task, step)]
    stamp = parent.rsplit('/',1)[-1]
    pid = f"t{task}s{step}@{stamp}"
    script, obs = load_step_data(parent, int(step))
    out.append(f"===== POINT {i}/6: {pid} =====")
    out.append(f"[TASK-DESC] {desc_by_id[int(task)]}")
    out.append(f"[STEP-CODE t{task} step {step}] ({len(script)} chars)")
    out.append(script)
    out.append(f"[OBS t{task} step {step} first 1200 chars]")
    obs_l = oneline(obs)
    out.append(obs_l[:1200] + (" ... [TRUNCATED]" if len(obs_l) > 1200 else ""))
    out.append("")

text = "\n".join(out)
hits = final_leak_check(text)
if hits:
    print("LEAK CHECK FAILED:", hits[:10], file=sys.stderr); sys.exit(1)
blocks = re.findall(r"\[STEP-CODE[^\]]*\] \((\d+) chars\)\n(.+?)\n\[OBS", text, re.DOTALL)
bad = [(n, c[:40]) for n, c in blocks if int(n) < 80 or '\n' not in c]
if bad:
    print("STEP-CODE BODY CHECK FAILED:", bad, file=sys.stderr); sys.exit(1)
open(OUT,'w').write(text)
print(f"OK: {len(blocks)} points, {len(text)} chars; code sizes: {[int(n) for n,_ in blocks]}")
