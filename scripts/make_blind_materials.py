#!/usr/bin/env python3
"""Regenerate blinded annotation materials (v2) for P2 sec4.2.

Fixes over v1 (ad-hoc generation, no archived script):
  1. Arm leakage: parent-run paths like /tmp/vf_work/sab_53/frontier/<uuid>/wd
     that appear verbatim inside step observations are redacted to <WORKDIR>
     (v1 leaked `frontier` in 3 points' OBS).
  2. Truncation: STEP-CODE cap raised 2600 -> 10000 chars (17 points were cut
     mid-script in v1); OBS cap raised 500 -> 1200.
  3. TASK-DESC now sourced directly from benchmark verified.parquet `task_inst`.
  4. Archived, deterministic script (this file) replaces the one-off command.

Blinding guarantees (checked at the end, hard-fail):
  no arm names (frontier/resample/local_replace), no model ids
  (gpt-5/qwen/deepseek/mini as whole words), no eval outcomes, no later-step
  content. Per-point inputs are limited to: task instruction, the code of that
  step only, and the observation of that step only.

Usage: python3 scripts/make_blind_materials.py [--code-cap N] [--obs-cap N]
Outputs: reports/annotation/blind_materials_v2.md
"""
import argparse
import json
import re
import sys

import pandas as pd

POINTS_PATH = 'reports/annotation/cf_points.json'
PARQUET = '/data/lab/sab_data/verified.parquet'
OUT_PATH = 'reports/annotation/blind_materials_v2.md'

ARM_PATH_RE = re.compile(
    r"/tmp/vf_work/sab_\d+/[A-Za-z_]+/[0-9a-f]{6,}/wd(?:/pred_results)?")
PARENT_RUN_RE = re.compile(
    r"runs/sab_\d+/(?:frontier|local_replace|frontier_resample|frontier_hint)/[\d]+-[\d]+")


def redact(text: str) -> str:
    text = ARM_PATH_RE.sub("<WORKDIR>", text)
    text = PARENT_RUN_RE.sub("<PARENT_RUN>", text)
    return text


def oneline(text: str) -> str:
    return text.replace("\r", " ").replace("\n", " | ").strip()


def load_step_data(parent_run: str, step_no: int):
    r = json.load(open(f"{parent_run}/result.json"))
    script = None
    for s in r.get("steps", []):
        if int(s.get("step")) == int(step_no):
            script = s.get("script") or ""
            break
    if script is None:
        script = open(f"{parent_run}/step_{int(step_no):02d}.py").read()
    obs = None
    with open(f"{parent_run}/trace.jsonl", errors="ignore") as f:
        for line in f:
            try:
                ev = json.loads(line)
            except Exception:
                continue
            if ev.get("event_type") != "tool_result":
                continue
            if int(ev.get("scientific_step_id") or 0) == int(step_no):
                obs = ev.get("tool_observation")
                break
    if obs is None:  # fall back: k-th tool_result matches k-th executed step
        idx, seen = 0, None
        with open(f"{parent_run}/trace.jsonl", errors="ignore") as f:
            for line in f:
                try:
                    ev = json.loads(line)
                except Exception:
                    continue
                if ev.get("event_type") == "tool_result":
                    idx += 1
                    if idx == int(step_no):
                        seen = ev.get("tool_observation")
                        break
        obs = seen or ""
    return redact(script), redact(obs)


LEAK_RE = re.compile(
    r"\b(frontier|resample|local_replace|frontier_hint|gpt-5|deepseek)\b"
    r"|\bQwen\d|(?<!deter)mini", re.IGNORECASE)


def final_leak_check(text: str):
    hits = []
    for m in LEAK_RE.finditer(text):
        ctx = text[max(0, m.start() - 40):m.end() + 40]
        if "deterministic" in ctx or "mini" in m.group(0).lower() and "deter" in ctx.lower():
            continue
        hits.append(m.group(0))
    return hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--code-cap", type=int, default=10000)
    ap.add_argument("--obs-cap", type=int, default=1200)
    args = ap.parse_args()

    pts = json.load(open(POINTS_PATH))["points"]
    pts = sorted(pts, key=lambda p: (str(p["task_id"]), int(p["step_no"]), p["parent_stamp"]))
    desc = pd.read_parquet(PARQUET)
    desc_by_id = {int(r["instance_id"]): str(r["task_inst"]) for _, r in desc.iterrows()}

    out = ["# P2 sec4.2 Blind Annotation Materials (v2)", "",
           "Generated by scripts/make_blind_materials.py (deterministic; arm/model info redacted).",
           "TASK-DESC is the benchmark task instruction verbatim ('Computational Analysis' is the",
           "original instruction for those tasks, not truncation).", ""]
    for i, p in enumerate(pts, 1):
        task, step = str(p["task_id"]), int(p["step_no"])
        parent = p["parent_run"]
        pid = f"t{task}s{step}@{p['parent_stamp']}"
        script, obs = load_step_data(parent, step)
        out.append(f"===== POINT {i}/38: {pid} =====")
        out.append(f"[TASK-DESC] {desc_by_id[int(task)]}")
        out.append(f"[STEP-CODE t{task} step {step}] ({len(script)} chars)")
        out.append(script[: args.code_cap] + ("\n... [TRUNCATED]" if len(script) > args.code_cap else ""))
        out.append(f"[OBS t{task} step {step} first {args.obs_cap} chars]")
        obs_l = oneline(obs)
        out.append(obs_l[: args.obs_cap] + (" ... [TRUNCATED]" if len(obs_l) > args.obs_cap else ""))
        out.append("")

    text = "\n".join(out)
    leaks = final_leak_check(text)
    if leaks:
        print("LEAK DETECTED:", leaks[:5], file=sys.stderr)
        sys.exit(1)
    open(OUT_PATH, "w").write(text)
    print(f"wrote {OUT_PATH}: {len(pts)} points, {len(text)} chars, leak check clean")


if __name__ == "__main__":
    main()
